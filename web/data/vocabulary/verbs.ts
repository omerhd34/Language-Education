export type EnglishVerb = {
  id: string;
  infinitive: string;
  pastSimple: string;
  pastParticiple: string;
  regular: boolean;
};

export const VERBS_REFERENCE_ID = "verbs";

function irregular(
  id: string,
  infinitive: string,
  pastSimple: string,
  pastParticiple: string,
): EnglishVerb {
  return {
    id,
    infinitive,
    pastSimple,
    pastParticiple,
    regular: false,
  };
}

function regularVerb(
  id: string,
  infinitive: string,
  pastSimple: string,
): EnglishVerb {
  return {
    id,
    infinitive,
    pastSimple,
    pastParticiple: pastSimple,
    regular: true,
  };
}

